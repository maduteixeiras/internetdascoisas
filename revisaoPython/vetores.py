nomes = ["Julia", "Maria", "Carla", "Enzo"]
numeros = [33, 11, 22, 56]

print(nomes[2])
# append - enserir novo elemento no final da lista
nomes.append("Lucas")
# insert - inserir novo elemento em uma posição específica da lista
numeros.insert(3, 50)
# pop - remover elemento de uma posição específica da lista
numeros.pop(1)
# remove - remover elemento pelo conteúdo da lista
nomes.remove("Carla")